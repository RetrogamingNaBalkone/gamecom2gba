"""Generate the SM8500 (game.com SM8521) SLEIGH specification.

The instruction encodings and semantics follow the Tigerbyte SM8521 core and
MAME's sm85ops.h. Register-file operands below 10h are modelled as the
sixteen banked registers r0-r15 (the bank selected by PS0 is not tracked).
Run from any directory: python generate.py > data/languages/sm8500.slaspec
"""

ALU = ["CMP", "ADD", "SUB", "ADC", "SBC", "AND", "OR", "XOR"]
COND = ["F", "LT", "LE", "ULE", "OV", "MI", "Z", "C", "T", "GE", "GT", "UGT", "NOV", "PL", "NZ", "NC"]
UN1A = ["CLR", "NEG", "COM", "RR", "RL", "RRC", "RLC", "SRL"]
UN1B = ["INC", "DEC", "SRA", "SLL", "DA", "SWAP", "PUSH", "POP"]

HEADER = r"""# SM8500 / SM8521 (Tiger game.com). Generated by analysis/SM8500/generate.py.
# Register-file addresses 00-0F refer to the banked registers r0-r15 selected by PS0.
define endian=big;
define alignment=1;
define space ram type=ram_space size=2 default;
define space register type=register_space size=1;

define register offset=0x00 size=1 [ r0 r1 r2 r3 r4 r5 r6 r7 r8 r9 r10 r11 r12 r13 r14 r15 ];
define register offset=0x00 size=2 [ rr0 rr2 rr4 rr6 rr8 rr10 rr12 rr14 ];
define register offset=0x20 size=2 [ PC SP ];
define register offset=0x28 size=1 [ CF ZF SF VF DF HF BF IF PS0 ];

define token op8(8) op=(0,7) oplo3=(0,2) oplo4=(0,3) opn3=(0,2) oppair=(0,2) opport=(0,2) opfam5=(3,7) opfam4=(4,7);
define token rtok(8) rval=(0,7) rhi=(4,7) rlo=(0,3) rwi=(1,3) rodd=(0,0);
define token rtok2(8) rval2=(0,7) rhi2=(4,7) rlo2=(0,3) rwi2=(1,3) rodd2=(0,0);
define token mtok(8) mmode=(6,7) mdst=(3,5) mdstw=(3,5) msrc=(0,2) msrcw=(0,2) msrcr=(0,2) msub=(0,2) mbit=(0,2) mhi=(3,7);
define token itok(8) imm8=(0,7) simm8=(0,7) signed;
define token itok2(8) imm8b=(0,7);
define token wtok(16) imm16=(0,15);
define token btok(8) bmode=(6,7) bbit=(0,2) bidx=(3,5);

attach variables [ rlo rlo2 ] [ r0 r1 r2 r3 r4 r5 r6 r7 r8 r9 r10 r11 r12 r13 r14 r15 ];
attach variables [ rwi rwi2 ] [ rr0 rr2 rr4 rr6 rr8 rr10 rr12 rr14 ];
attach variables [ mdst msrcr oplo3 bidx ] [ r0 r1 r2 r3 r4 r5 r6 r7 ];
attach variables [ mdstw msrcw oppair ] [ rr0 rr8 rr2 rr10 rr4 rr12 rr6 rr14 ];

macro zs8(v) { ZF = v == 0; SF = v s< 0; }
macro zs16(v) { ZF = v == 0; SF = v s< 0; }
macro push16(v) { SP = SP - 2; *:2 SP = v; }
macro pop16(v) { v = *:2 SP; SP = SP + 2; }
macro push8(v) { SP = SP - 1; *:1 SP = v; }
macro pop8(v) { v = *:1 SP; SP = SP + 1; }

# Byte register-file operand: banked register below 10h, RAM/I-O otherwise.
RB: rlo is rhi=0 & rlo { export rlo; }
RB: "R"^rval is rval { export *:1 rval; }
RB2: rlo2 is rhi2=0 & rlo2 { export rlo2; }
RB2: "R"^rval2 is rval2 { export *:1 rval2; }
RW: rwi is rhi=0 & rodd=0 & rwi { export rwi; }
RW: "RR"^rval is rval { export *:2 rval; }
RW2: rwi2 is rhi2=0 & rodd2=0 & rwi2 { export rwi2; }
RW2: "RR"^rval2 is rval2 { export *:2 rval2; }

# Byte memory through an 8-bit pointer register.
PB: "@"^msrcr is mmode=0 & msrcr { local a:2 = zext(msrcr); export *:1 a; }
PB: "("^msrcr^")+" is mmode=1 & msrcr { local a:2 = zext(msrcr); msrcr = msrcr + 1; export *:1 a; }
PB: "@"^imm8 is mmode=2 & msrc=0; imm8 { export *:1 imm8; }
PB: imm8^"("^msrcr^")" is mmode=2 & msrcr; imm8 { local a:2 = zext(msrcr) + imm8; export *:1 a; }
PB: "-("^msrcr^")" is mmode=3 & msrcr { msrcr = msrcr - 1; local a:2 = zext(msrcr); export *:1 a; }

# Byte memory through a 16-bit pointer pair.
PW: "@"^msrcw is mmode=0 & msrcw { local a:2 = msrcw; export *:1 a; }
PW: "("^msrcw^")+" is mmode=1 & msrcw { local a:2 = msrcw; msrcw = msrcw + 1; export *:1 a; }
PW: "@"^imm16 is mmode=2 & msrc=0; imm16 { export *:1 imm16; }
PW: imm16^"("^msrcw^")" is mmode=2 & msrcw; imm16 { local a:2 = msrcw + imm16; export *:1 a; }
PW: "-("^msrcw^")" is mmode=3 & msrcw { msrcw = msrcw - 1; local a:2 = msrcw; export *:1 a; }

# Word memory through a 16-bit pointer pair (auto step 2).
PW2: "@"^msrcw is mmode=0 & msrcw { local a:2 = msrcw; export *:2 a; }
PW2: "("^msrcw^")+" is mmode=1 & msrcw { local a:2 = msrcw; msrcw = msrcw + 2; export *:2 a; }
PW2: "@"^imm16 is mmode=2 & msrc=0; imm16 { export *:2 imm16; }
PW2: imm16^"("^msrcw^")" is mmode=2 & msrcw; imm16 { local a:2 = msrcw + imm16; export *:2 a; }
PW2: "-("^msrcw^")" is mmode=3 & msrcw { msrcw = msrcw - 2; local a:2 = msrcw; export *:2 a; }

# Direct-page bit operand of 1C/1D/2A/2B.
BITADDR: "$FF"^imm8 is bidx=0 & bbit; imm8 { local a:2 = 0xff00 + imm8; export *:1 a; }
BITADDR: imm8^"("^bidx^")" is bidx & bbit; imm8 { local a:2 = zext(bidx) + imm8; export *:1 a; }

REL: dest is simm8 [ dest = inst_next + simm8; ] { export *:1 dest; }
ABS: imm16 is imm16 { export *:1 imm16; }
PORT: "R"^p is opport [ p = 0x10 + opport; ] { export *:1 p; }
CALSDEST: dest is oplo4; imm8 [ dest = 0x1000 | (oplo4 << 8) | imm8; ] { export *:1 dest; }

CC: "F" is oplo4=0 { export 0:1; }
CC: "LT" is oplo4=1 { tmp:1 = SF != VF; export tmp; }
CC: "LE" is oplo4=2 { tmp:1 = ZF || (SF != VF); export tmp; }
CC: "ULE" is oplo4=3 { tmp:1 = CF || ZF; export tmp; }
CC: "OV" is oplo4=4 { export VF; }
CC: "MI" is oplo4=5 { export SF; }
CC: "Z" is oplo4=6 { export ZF; }
CC: "C" is oplo4=7 { export CF; }
CC: "T" is oplo4=8 { export 1:1; }
CC: "GE" is oplo4=9 { tmp:1 = SF == VF; export tmp; }
CC: "GT" is oplo4=10 { tmp:1 = !ZF && (SF == VF); export tmp; }
CC: "UGT" is oplo4=11 { tmp:1 = !CF && !ZF; export tmp; }
CC: "NOV" is oplo4=12 { tmp:1 = !VF; export tmp; }
CC: "PL" is oplo4=13 { tmp:1 = !SF; export tmp; }
CC: "NZ" is oplo4=14 { tmp:1 = !ZF; export tmp; }
CC: "NC" is oplo4=15 { tmp:1 = !CF; export tmp; }
"""


def alu(op, d, s, size):
    """P-code for an ALU operation d op= s of the given byte size."""
    zs = "zs8" if size == 1 else "zs16"
    if op == "CMP":
        return f"local t:{size} = {d} - {s}; CF = {d} < {s}; VF = sborrow({d}, {s}); {zs}(t);"
    if op == "ADD":
        return f"CF = carry({d}, {s}); VF = scarry({d}, {s}); {d} = {d} + {s}; {zs}({d});"
    if op == "SUB":
        return f"CF = {d} < {s}; VF = sborrow({d}, {s}); {d} = {d} - {s}; {zs}({d});"
    if op == "ADC":
        return (f"local c:{size} = zext(CF); local t:{size} = {d} + {s}; "
                f"CF = carry({d}, {s}) || carry(t, c); VF = scarry({d}, {s}) ^^ scarry(t, c); "
                f"{d} = t + c; {zs}({d});")
    if op == "SBC":
        return (f"local c:{size} = zext(CF); local t:{size} = {d} - {s}; "
                f"CF = ({d} < {s}) || (t < c); VF = sborrow({d}, {s}) ^^ sborrow(t, c); "
                f"{d} = t - c; {zs}({d});")
    sym = {"AND": "&", "OR": "|", "XOR": "^"}[op]
    return f"{d} = {d} {sym} {s}; {zs}({d});"


def unary(name, v):
    if name == "CLR":
        return f"{v} = 0;"
    if name == "NEG":
        return f"VF = {v} == 0x80; {v} = -{v}; CF = {v} == 0; zs8({v});"
    if name == "COM":
        return f"{v} = ~{v}; zs8({v});"
    if name == "RR":
        return f"CF = ({v} & 1) != 0; {v} = ({v} >> 1) | ({v} << 7); zs8({v});"
    if name == "RL":
        return f"CF = ({v} & 0x80) != 0; {v} = ({v} << 1) | ({v} >> 7); zs8({v});"
    if name == "RRC":
        return f"local c:1 = CF; CF = ({v} & 1) != 0; {v} = ({v} >> 1) | (c << 7); zs8({v});"
    if name == "RLC":
        return f"local c:1 = CF; CF = ({v} & 0x80) != 0; {v} = ({v} << 1) | c; zs8({v});"
    if name == "SRL":
        return f"CF = ({v} & 1) != 0; {v} = {v} >> 1; zs8({v});"
    if name == "INC":
        return f"VF = {v} == 0x7f; {v} = {v} + 1; zs8({v});"
    if name == "DEC":
        return f"VF = {v} == 0x80; {v} = {v} - 1; zs8({v});"
    if name == "SRA":
        return f"CF = ({v} & 1) != 0; {v} = {v} s>> 1; zs8({v});"
    if name == "SLL":
        return f"CF = ({v} & 0x80) != 0; {v} = {v} << 1; zs8({v});"
    if name == "DA":
        return f"{v} = decimal_adjust({v}, CF, HF, DF); zs8({v});"
    if name == "SWAP":
        return f"{v} = ({v} >> 4) | ({v} << 4);"
    if name == "PUSH":
        return f"push8({v});"
    if name == "POP":
        return f"pop8({v});"
    raise KeyError(name)


def main():
    out = [HEADER]
    out.append("define pcodeop decimal_adjust;\ndefine pcodeop stop;\ndefine pcodeop halt;\n"
               "define pcodeop bit_move;\ndefine pcodeop dm;\n")
    o = out.append
    unary_names = UN1A + UN1B
    for i, name in enumerate(unary_names):
        if name in ("PUSH", "POP"):
            continue
        o(f":{name} RB is op={i:#04x}; RB {{ {unary('' + name, 'RB')} }}")
    o(":PUSH RB is op=0x0e; RB { push8(RB); }")
    o(":POP RB is op=0x0f; RB { pop8(RB); }")
    for i, name in enumerate(ALU):
        o(f":{name} mdst,msrcr is op={0x10 + i:#04x}; mmode=0 & mdst & msrcr {{ {alu(name, 'mdst', 'msrcr', 1)} }}")
    o(":INCW RW is op=0x18; RW { CF = carry(RW, 1); VF = scarry(RW, 1); RW = RW + 1; zs16(RW); }")
    o(":DECW RW is op=0x19; RW { CF = RW < 1; VF = sborrow(RW, 1); RW = RW - 1; zs16(RW); }")
    for i, name in enumerate(UN1A):
        o(f":{name} \"@\"^mdst is op=0x1a; mmode=0 & mdst & msub={i} "
          f"{{ local a:2 = zext(mdst); local v:1 = *:1 a; {unary(name, 'v')} *:1 a = v; }}")
    for i, name in enumerate(UN1B):
        o(f":{name} \"@\"^mdst is op=0x1b; mmode=0 & mdst & msub={i} "
          f"{{ local a:2 = zext(mdst); local v:1 = *:1 a; {unary(name, 'v')} *:1 a = v; }}")
    o(":BCLR BITADDR,\"#\"^bbit is op=0x1c; BITADDR & bbit ... { BITADDR = BITADDR & ~(1 << bbit); }")
    o(":BSET BITADDR,\"#\"^bbit is op=0x1d; BITADDR & bbit ... { BITADDR = BITADDR | (1 << bbit); }")
    o(":PUSHW RW is op=0x1e; RW { push16(RW); }")
    o(":POPW RW is op=0x1f; RW { pop16(RW); }")
    for i, name in enumerate(ALU):
        o(f":{name} mdst,PB is op={0x20 + i:#04x}; (mdst ... & PB) {{ {alu(name, 'mdst', 'PB', 1)} }}")
    o(":MOV mdst,PB is op=0x28; (mdst ... & PB) { mdst = PB; }")
    o(":MOV PB,mdst is op=0x29; (mdst ... & PB) { PB = mdst; }")
    o(":BBC BITADDR,\"#\"^bbit,REL is op=0x2a; (BITADDR & bbit ...); REL "
      "{ if ((BITADDR & (1 << bbit)) == 0) goto REL; }")
    o(":BBS BITADDR,\"#\"^bbit,REL is op=0x2b; (BITADDR & bbit ...); REL "
      "{ if ((BITADDR & (1 << bbit)) != 0) goto REL; }")
    o(":EXTS RW is op=0x2c; RW { local b:1 = RW:1; RW = sext(b); }")
    o(":DM imm8 is op=0x2d; imm8 { dm(imm8:1); }")
    o(":MOV \"PS0\",imm8 is op=0x2e; imm8 { PS0 = imm8; }")
    o(":BTST RB,imm8 is op=0x2f; RB; imm8 { VF = 0; ZF = (RB & imm8) == 0; }")
    for i, name in enumerate(ALU):
        o(f":{name} mdst,PW is op={0x30 + i:#04x}; (mdst ... & PW) {{ {alu(name, 'mdst', 'PW', 1)} }}")
    o(":MOV mdst,PW is op=0x38; (mdst ... & PW) { mdst = PW; }")
    o(":MOV PW,mdst is op=0x39; (mdst ... & PW) { PW = mdst; }")
    o(":MOVW mdstw,PW2 is op=0x3a; (mdstw ... & PW2) { mdstw = PW2; }")
    o(":MOVW PW2,mdstw is op=0x3b; (mdstw ... & PW2) { PW2 = mdstw; }")
    o(":MOVW mdstw,msrcw is op=0x3c; mmode=0 & mdstw & msrcw { mdstw = msrcw; }")
    o(":DM RB is op=0x3d; RB { dm(RB); }")
    o(":JMP \"@\"^msrcw is op=0x3e; mmode=0 & msrcw { goto [msrcw]; }")
    o(":JMP \"@\"^imm16 is op=0x3e; mmode=1 & mdst=0; imm16 { local a:2 = imm16; local t:2 = *:2 a; goto [t]; }")
    o(":JMP \"@\"^imm16^\"(\"^mdst^\")\" is op=0x3e; mmode=1 & mdst; imm16 "
      "{ local a:2 = zext(mdst); a = a + imm16; local t:2 = *:2 a; goto [t]; }")
    o(":CALL \"@\"^msrcw is op=0x3f; mmode=0 & msrcw { local ret:2 = inst_next; push16(ret); call [msrcw]; }")
    o(":CALL \"@\"^imm16 is op=0x3f; mmode=1 & mdst=0; imm16 "
      "{ local a:2 = imm16; local t:2 = *:2 a; local ret:2 = inst_next; push16(ret); call [t]; }")
    o(":CALL \"@\"^imm16^\"(\"^mdst^\")\" is op=0x3f; mmode=1 & mdst; imm16 "
      "{ local a:2 = zext(mdst); a = a + imm16; local t:2 = *:2 a; local ret:2 = inst_next; push16(ret); call [t]; }")
    # Two register-file operands: first byte is the source, second the destination.
    for i, name in enumerate(ALU):
        o(f":{name} RB2,RB is op={0x40 + i:#04x}; RB; RB2 {{ {alu(name, 'RB2', 'RB', 1)} }}")
    o(":MOV RB2,RB is op=0x48; RB; RB2 { RB2 = RB; }")
    o(":CALL ABS is op=0x49; ABS { local ret:2 = inst_next; push16(ret); call ABS; }")
    o(":MOVW RW2,RW is op=0x4a; RW; RW2 { RW2 = RW; }")
    o(":MOVW RW,\"#\"^imm16 is op=0x4b; RW; imm16 { RW = imm16; }")
    o(":MULT RW2,RB is op=0x4c; RB; RW2 { local lo:1 = RW2:1; RW2 = zext(lo) * zext(RB); ZF = RW2 == 0; VF = 0; }")
    o(":MULT RW2,\"#\"^imm8 is op=0x4d; imm8; RW2 { local lo:1 = RW2:1; RW2 = zext(lo) * imm8; ZF = RW2 == 0; VF = 0; }")
    o(":BMOV RB,\"#\"^bbit,\"BF\" is op=0x4e; bmode=1 & bbit; RB "
      "{ RB = (RB & ~(1 << bbit)) | (BF << bbit); }")
    o(":BMOV \"BF\",RB,\"#\"^bbit is op=0x4e; bmode=0 & bbit; RB { BF = (RB >> bbit) & 1; ZF = BF == 0; }")
    for i, name in enumerate(["BCMP", "BAND", "BOR", "BXOR"]):
        sem = {"BCMP": "ZF = b == BF;", "BAND": "BF = b & BF; ZF = BF == 0;",
               "BOR": "BF = b | BF; ZF = BF == 0;", "BXOR": "BF = b ^ BF; ZF = BF == 0;"}[name]
        o(f":{name} \"BF\",RB,\"#\"^bbit is op=0x4f; bmode={i} & bbit; RB "
          f"{{ local b:1 = (RB >> bbit) & 1; {sem} }}")
    for i, name in enumerate(ALU):
        o(f":{name} RB2,\"#\"^imm8 is op={0x50 + i:#04x}; imm8; RB2 {{ {alu(name, 'RB2', 'imm8', 1)} }}")
    o(":MOV RB2,\"#\"^imm8 is op=0x58; imm8; RB2 { RB2 = imm8; }")
    for opc, mnem in ((0x5a, "CMP"), (0x5b, "MOV")):
        forms = [
            ("\"@\"^msrcw", "mmode=0 & msrcw; imm8", "local a:2 = msrcw;"),
            ("\"(\"^msrcw^\")+\"", "mmode=1 & msrcw; imm8", "local a:2 = msrcw; msrcw = msrcw + 1;"),
            ("imm8b^\"(\"^msrcw^\")\"", "mmode=2 & msrcw; imm8b; imm8", "local a:2 = msrcw + imm8b;"),
            ("\"-(\"^msrcw^\")\"", "mmode=3 & msrcw; imm8", "msrcw = msrcw - 1; local a:2 = msrcw;"),
        ]
        for text, pattern, address in forms:
            body = ("local m:1 = *:1 a; local t:1 = m - imm8; CF = m < imm8; VF = sborrow(m, imm8); zs8(t);"
                    if mnem == "CMP" else "*:1 a = imm8;")
            o(f":{mnem} {text},\"#\"^imm8 is op={opc:#04x}; {pattern} {{ {address} {body} }}")
    o(":DIV RW2,RW is op=0x5c; RW; RW2 { local dv:1 = RW:1; local d:2 = zext(dv); "
      "VF = d == 0; local q:2 = RW2 / d; local r:2 = RW2 % d; RW = (RW & 0x00ff) | (r << 8); "
      "RW2 = q; ZF = q == 0; }")
    o(":DIV RW2,\"#\"^imm8 is op=0x5d; imm8; RW2 { local d:2 = imm8; VF = d == 0; RW2 = RW2 / d; ZF = RW2 == 0; }")
    o(":MOVM RB,\"#\"^imm8b,RB2 is op=0x5e; RB; imm8b; RB2 { RB = (RB & imm8b) | RB2; }")
    o(":MOVM RB,\"#\"^imm8b,\"#\"^imm8 is op=0x5f; RB; imm8b; imm8 { RB = (RB & imm8b) | imm8; }")
    for i, name in enumerate(ALU):
        o(f":{name}W RW2,RW is op={0x60 + i:#04x}; RW; RW2 {{ {alu(name, 'RW2', 'RW', 2)} }}")
    for i, name in enumerate(ALU):
        o(f":{name}W RW,\"#\"^imm16 is op={0x68 + i:#04x}; RW; imm16 {{ {alu(name, 'RW', 'imm16', 2)} }}")
    o(":DBNZ oplo3,REL is opfam5=0x0e & oplo3; REL { oplo3 = oplo3 - 1; if (oplo3 != 0) goto REL; }")
    o(":MOVW oppair,\"#\"^imm16 is opfam5=0x0f & oppair; imm16 { oppair = imm16; }")
    o(":BBC RB,\"#\"^opn3,REL is opfam5=0x10 & opn3; RB; REL "
      "{ if ((RB & (1 << opn3)) == 0) goto REL; }")
    o(":BBS RB,\"#\"^opn3,REL is opfam5=0x11 & opn3; RB; REL "
      "{ if ((RB & (1 << opn3)) != 0) goto REL; }")
    o(":JMP CC,ABS is opfam4=0x9 & CC; ABS { if (CC) goto ABS; }")
    o(":JMP ABS is op=0x98; ABS { goto ABS; }")
    o(":BCLR RB,\"#\"^opn3 is opfam5=0x14 & opn3; RB { RB = RB & ~(1 << opn3); }")
    o(":BSET RB,\"#\"^opn3 is opfam5=0x15 & opn3; RB { RB = RB | (1 << opn3); }")
    o(":MOV oplo3,RB is opfam5=0x16 & oplo3; RB { oplo3 = RB; }")
    o(":MOV RB,oplo3 is opfam5=0x17 & oplo3; RB { RB = oplo3; }")
    o(":MOV oplo3,\"#\"^imm8 is opfam5=0x18 & oplo3; imm8 { oplo3 = imm8; }")
    o(":MOV PORT,\"#\"^imm8 is opfam5=0x19 & PORT; imm8 { PORT = imm8; }")
    o(":BR CC,REL is opfam4=0xd & CC; REL { if (CC) goto REL; }")
    o(":BR REL is op=0xd8; REL { goto REL; }")
    o(":CALS CALSDEST is (opfam4=0xe ... & CALSDEST) { local ret:2 = inst_next; push16(ret); call CALSDEST; }")
    o(":STOP is op=0xf0 { stop(); }")
    o(":HALT is op=0xf1 { halt(); }")
    o(":RET is op=0xf8 { local t:2 = *:2 SP; SP = SP + 2; return [t]; }")
    o(":IRET is op=0xf9 { SP = SP + 1; local t:2 = *:2 SP; SP = SP + 2; return [t]; }")
    o(":CLRC is op=0xfa { CF = 0; }")
    o(":COMC is op=0xfb { CF = !CF; }")
    o(":SETC is op=0xfc { CF = 1; }")
    o(":EI is op=0xfd { IF = 1; }")
    o(":DI is op=0xfe { IF = 0; }")
    o(":NOP is op=0xff { }")
    print("\n".join(out))


if __name__ == "__main__":
    main()
